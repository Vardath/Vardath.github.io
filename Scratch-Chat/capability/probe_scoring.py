"""Strict, transparent checks of generated answers; NOT a readiness certification.

These fixed probes are development diagnostics, not an independent benchmark.
All answers must be generated by the checkpoint, not a hardcoded response table.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


def score(report: dict) -> dict:
    probes = report.get("probes")
    if not isinstance(probes, list):
        raise ValueError("Missing generated probes")
    by_id = {p["id"]: p for p in probes}
    if len(by_id) != len(probes):
        raise ValueError("Duplicate probe identifiers")
    required = {"greeting", "basic_fact", "instruction", "short_explanation",
                "multi_turn_memory", "refusal"}
    if not required.issubset(by_id):
        raise ValueError("Missing required generation probes")
    checks = {
        "basic_fact": bool(re.search(r"(?<!\w)(?:4|four)(?!\w)", by_id["basic_fact"]["response"].lower())),
        "instruction": by_id["instruction"]["response"].strip().lower() == "blue",
        "multi_turn_memory": bool(re.search(r"(?<!\w)violet(?!\w)", by_id["multi_turn_memory"]["response"].lower())),
    }
    return {
        "assessment_type": "fixed_probe_development_checks",
        "ready_for_conversation": False,
        "checkpoint_step": report.get("checkpoint_step"),
        "checks": checks,
        "passed": sum(checks.values()),
        "total": len(checks),
        "limitations": "Three fixed, easily overfit development checks. No independent benchmark, factual reliability, safety or human assessment. No readiness inference.",
    }


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--probes", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    args = p.parse_args()
    result = score(json.loads(args.probes.read_text(encoding="utf-8")))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result))


if __name__ == "__main__":
    main()
